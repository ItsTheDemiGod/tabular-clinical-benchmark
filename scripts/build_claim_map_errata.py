r"""Phase 4e: writes paper/evidence/claim_map_errata.md (claim_map.md itself is frozen, never edited).

Erratum for claim_map.md section C7: its columns "smallest drop" / "largest drop" label the MORE NEGATIVE
AUROC degradation as "smallest" and the less negative as "largest". Here "largest drop" = most negative
degradation (degradation = perturbed AUROC minus the model's own clean AUROC), "smallest drop" = the
least negative one. Everything is computed from paper/evidence/numbers.json; nothing is typed by hand.
Also provides `check_sheet_c7()`, the consistency check of the drafting sheet's C7 rows.
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))
from analysis.constants import MODELS

EVID = PROJECT_ROOT / "paper" / "evidence"
OUT = EVID / "claim_map_errata.md"
PERTURBATIONS = (("30% missing", "miss30"), ("noise 0.5 (original)", "noise50-orig"), ("noise 0.5 (continuous-only)", "noise50-cont"))
SETS = (("ALL5", "all5"), ("NO_CKD", "nockd"))


def load_numbers() -> dict[str, dict]:
    return {e["key"]: e for e in json.loads((EVID / "numbers.json").read_text(encoding="utf-8"))}


def compute(num: dict[str, dict]) -> list[dict]:
    """One row per (perturbation, set): the models with the largest (most negative) and smallest AUROC drop."""
    rows = []
    for plabel, pk in PERTURBATIONS:
        for slabel, sk in SETS:
            keys = {m: f"auroc-{pk}-degradation-{m}-{sk}" for m in MODELS}
            vals = {m: num[k]["value"] for m, k in keys.items()}
            big, small = min(vals, key=vals.get), max(vals, key=vals.get)
            rows.append({"perturbation": plabel, "set": slabel,
                         "largest": (big, keys[big], num[keys[big]]["formatted"], vals[big]),
                         "smallest": (small, keys[small], num[keys[small]]["formatted"], vals[small]),
                         "range": vals[small] - vals[big]})
    return rows


def claim_map_c7_table() -> list[dict]:
    """The C7 table of claim_map.md as printed: (perturbation, set, 'smallest drop' model, 'largest drop' model)."""
    sec = (EVID / "claim_map.md").read_text(encoding="utf-8").split("## C7.", 1)[1].split("\n## C8.", 1)[0]
    out = []
    for line in sec.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 5 and cells[1] in ("ALL5", "NO_CKD"):
            out.append({"perturbation": cells[0], "set": cells[1],
                        "smallest_label": re.search(r"\((\w+)\)", cells[2]).group(1),
                        "largest_label": re.search(r"\((\w+)\)", cells[3]).group(1)})
    return out


def check_sheet_c7(num: dict[str, dict], sheet_csv: Path = EVID / "drafting_sheet.csv") -> list[str]:
    """Problems found in the drafting sheet's C7 rows (empty list = consistent with numbers.json)."""
    problems = []
    with sheet_csv.open(encoding="utf-8", newline="") as fh:
        rows = [r for r in csv.DictReader(fh) if "C7" in r["claim_status"] and r["item_id"].startswith("VC-")]
    if not rows:
        problems.append("no C7 rows found in the drafting sheet")
    for r in rows:
        keys, vals = r["keys"].split("|"), r["values"].split("|")
        if len(keys) != len(vals):
            problems.append(f"{r['item_id']}: {len(keys)} keys but {len(vals)} values")
            continue
        for k, v in zip(keys, vals):
            if k not in num or num[k]["formatted"] != v:
                problems.append(f"{r['item_id']}: {k} value {v!r} != numbers.json")
        if re.search(r"smallest|largest", r["fact_label"], re.I):
            problems.append(f"{r['item_id']}: label uses 'smallest/largest' wording: {r['fact_label']!r}")
    return problems


def render(rows: list[dict], printed: list[dict], problems: list[str]) -> str:
    L = ["# Errata for claim_map.md, section C7 (generated by scripts/build_claim_map_errata.py; claim_map.md is NOT edited)", "",
         "`claim_map.md` C7 labels the MORE NEGATIVE AUROC degradation \"smallest drop\" and the LESS negative one \"largest drop\".",
         "Here: **largest drop = most negative degradation**, **smallest drop = least negative degradation** (degradation = perturbed AUROC minus the model's own clean AUROC, dataset-averaged). "
         "Every value below is read from `numbers.json` (keys shown).", "",
         "| perturbation | set | largest drop: model (key) | formatted (unrounded) | smallest drop: model (key) | formatted (unrounded) | range |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        (bm, bk, bf, bv), (sm, sk, sf, sv) = r["largest"], r["smallest"]
        L.append(f"| {r['perturbation']} | {r['set']} | {bm} (`{bk}`) | {bf} ({bv:.6f}) | {sm} (`{sk}`) | {sf} ({sv:.6f}) | {r['range']:.4f} |")
    L += ["", "## Comparison with the C7 table printed in claim_map.md", "",
          "| perturbation | set | claim_map.md \"smallest drop\" | by value: largest drop | claim_map.md \"largest drop\" | by value: smallest drop | swapped? |", "|---|---|---|---|---|---|---|"]
    by = {(r["perturbation"], r["set"]): r for r in rows}
    for p in printed:
        r = by[(p["perturbation"], p["set"])]
        swapped = p["smallest_label"] == r["largest"][0] and p["largest_label"] == r["smallest"][0]
        L.append(f"| {p['perturbation']} | {p['set']} | {p['smallest_label']} | {r['largest'][0]} | {p['largest_label']} | {r['smallest'][0]} | {'yes' if swapped else 'NO'} |")
    L += ["", "## Consistency of the drafting sheet's C7 rows (VC-001..VC-014)", ""]
    L += [f"- PROBLEM: {p}" for p in problems] or ["- All C7 rows list only numbers-book keys with their exact formatted values and use no \"smallest/largest\" wording: consistent."]
    return "\n".join(L) + "\n"


def main() -> None:
    num = load_numbers()
    text = render(compute(num), claim_map_c7_table(), check_sheet_c7(num))
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(text)


if __name__ == "__main__":
    main()
