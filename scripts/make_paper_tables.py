DATASET_NAME = {"pima_diabetes": "Pima diabetes", "heart_cleveland": "Heart Cleveland", "ckd": "CKD",
                "ilpd": "ILPD", "breast_wisconsin": "Breast Wisconsin"}
# The ONLY strings containing digits that may appear outside \N{...} arguments in Table I.
TABLE1_HEADER_TEXT = [r"Min.\ train ($f{=}0.1$)", r"\setlength{\tabcolsep}{3pt}"]  # fixed header text + one layout directive
TABLE1_WIDE = True  # table*: a manual width estimate (formatted values + headers, ~4 in) exceeds one IEEE column (3.45 in); the build_numbers estimator counts macro key text, so it is not usable here


def build_datasets_table(numbers: dict[str, dict], wide: bool = TABLE1_WIDE) -> str:
    r"""Table I: one row per dataset; every numeric cell is a \N{key} macro."""
    def k(tmpl: str, ds: str) -> str:
        key = tmpl.format(d=ds.replace("_", "-"))
        if key not in numbers or numbers[key]["undefined"]:
            raise KeyError(f"numbers.json key missing or undefined: {key}")
        return "\\N{" + key + "}"
    env = "table*" if wide else "table"
    lines = [
        "% Generated by scripts/make_paper_tables.py -- do not edit by hand.",
        "% Every numeric cell is a numbers-book macro (keys in paper/evidence/numbers.json).",
        "\\begin{" + env + "}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{TODO: caption}",
        "\\label{tab:datasets}",
        "\\begin{tabular}{lrcrrr}",
        "\\toprule",
        r"Dataset & Samples & Features (num/cat) & Pos.\ (\%) & Missing (\%) & " + TABLE1_HEADER_TEXT[0] + r" \\",
        "\\midrule",
    ]
    for ds in DATASETS_ALL5:
        lines.append(" & ".join([
            DATASET_NAME[ds], k("rows-used-{d}", ds),
            f"{k('raw-features-{d}', ds)} ({k('n-numeric-{d}', ds)}/{k('n-categorical-{d}', ds)})",
            k("positive-fraction-{d}", ds), k("missing-fraction-{d}", ds), k("min-train-f0.1-{d}", ds)]) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{" + env + "}", ""]
    return "\n".join(lines)


def build_supp_search_spaces() -> tuple[str, pd.DataFrame]:
    ss = json.loads((PROJECT_ROOT / "paper/evidence/protocol_facts.json").read_text(encoding="utf-8"))["search_space"]
    rows = [{"model": m, "parameter": p["name"], "type": p["type"], "low": "" if p["low"] is None else p["low"],
             "high": "" if p["high"] is None else p["high"], "log_scale": p["log"],
             "choices": "" if p["choices"] is None else " ".join(str(c) for c in p["choices"])}
            for m in MODELS if m in ss for p in ss[m]]
    df = pd.DataFrame(rows)
    return _longtable(df, "Hyperparameter search space of each model",
                      "paper/evidence/protocol_facts.json (search_space)"), df


def build_supp_explanations() -> tuple[str, pd.DataFrame]:
    top = pd.read_csv(PROJECT_ROOT / "results/phase3d/top_features.csv")
    pl = pd.read_csv(PROJECT_ROOT / "results/phase3d/plausibility.csv")
    rows = []
    for ds in DATASETS_ALL5:
        for m in ("logreg", "rf", "mlp"):
            t = top[(top.dataset == ds) & (top.model == m)].sort_values("rank")
            feats = ", ".join(f"{r.feature}{'*' if r.on_clinical_list else ''}" for r in t.itertuples())
            p = pl[(pl.dataset == ds) & (pl.model == m)].iloc[0]
            rows.append({"dataset": ds, "model": m, "top5_features": feats,
                         "precision_ci": f"{_fmt(p.precision_mean, 2)} [{_fmt(p.precision_ci_lo, 2)}, {_fmt(p.precision_ci_hi, 2)}]",
                         "chance_precision": _fmt(p.chance_precision, 3)})
    df = pd.DataFrame(rows)
    return _longtable(df, "Top-5 features (* = on the pre-registered clinical list), precision against the list and chance level",
                      "results/phase3d/top_features.csv, results/phase3d/plausibility.csv"), df


def main() -> None:
    print(f"sys.executable = {sys.executable}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tex, report = build_main_table(load_numbers())
    (OUT_DIR / "table_main.tex").write_text(tex, encoding="utf-8", newline="\n")
    for r in report:
        print(r)
    (OUT_DIR / "table_datasets.tex").write_text(build_datasets_table(load_numbers()), encoding="utf-8", newline=chr(10))
    for name, (tex_s, df) in (("supp_slopes_per_dataset", build_supp_slopes()),
                              ("supp_noise_comparison", build_supp_noise()),
                              ("supp_search_spaces", build_supp_search_spaces()),
                              ("supp_explanations", build_supp_explanations())):
        (OUT_DIR / f"{name}.tex").write_text(tex_s, encoding="utf-8", newline="\n")
        df.to_csv(OUT_DIR / f"{name}.csv", index=False, lineterminator="\n")
        print(f"wrote {name} ({len(df)} rows)")


if __name__ == "__main__":
    main()
