"""Phase 4c: the main paper table (only \\N{key} macros) and two supplementary tables.

paper/tables/table_main.tex : every numeric cell is \\N{key}; the best value per column
    (by the UNROUNDED value in numbers.json) is wrapped in \\textbf. No prose, no typed digits
    except the fixed column-header strings in HEADER_TEXT.
paper/tables/supp_*.tex/.csv: supplementary (arXiv/repository only); numbers are written
    from the result CSVs and carry their source file names in a header comment.
Reads result files only; never fits anything. Deterministic (byte-identical on rerun).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import pandas as pd

from analysis.constants import DATASETS_ALL5, DATASETS_NO_CKD, MODELS

NUMBERS_JSON = PROJECT_ROOT / "paper" / "evidence" / "numbers.json"
OUT_DIR = PROJECT_ROOT / "paper" / "tables"

MODEL_NAME = {"logreg": "LogReg", "rf": "RF", "xgb": "XGBoost", "lgbm": "LightGBM",
              "mlp": "MLP", "ftt": "FT-Transformer", "tabnet": "TabNet"}

# The ONLY strings containing digits that may appear outside \N{...} arguments.
HEADER_TEXT = [
    r"AUROC, $f{=}1.0$", r"AUROC, $f{=}0.1$", r"Log loss, $f{=}1.0$", r"Log loss, $f{=}0.1$",
    r"Slope, $f{=}0.1$", "ALL5",
]

# Column spec: (header group, sub-header, key template, direction)
# direction: "max" (higher better), "min" (lower better), "one" (closest to 1)
COLUMNS: list[tuple[str, str, str, str]] = [
    ("auroc1", "ALL5", "auroc-mean-{m}-all5-f1.0", "max"),
    ("auroc1", "NO\\_CKD", "auroc-mean-{m}-nockd-f1.0", "max"),
    ("auroc01", "ALL5", "auroc-mean-{m}-all5-f0.1", "max"),
    ("auroc01", "NO\\_CKD", "auroc-mean-{m}-nockd-f0.1", "max"),
    ("ll1", "ALL5", "logloss-mean-{m}-all5-f1.0", "min"),
    ("ll01", "ALL5", "logloss-mean-{m}-all5-f0.1", "min"),
    ("slope", "NO\\_CKD", "slope-{m}-nockd-f0.1", "one"),
]
GROUP_HEADER = {"auroc1": HEADER_TEXT[0], "auroc01": HEADER_TEXT[1], "ll1": HEADER_TEXT[2],
                "ll01": HEADER_TEXT[3], "slope": HEADER_TEXT[4]}


def best_indices(values: list[float], direction: str) -> list[int]:
    """Indices of the best value(s) by UNROUNDED comparison (exact ties all returned)."""
    if direction == "max":
        target = max(values)
    elif direction == "min":
        target = min(values)
    elif direction == "one":
        target = min(values, key=lambda v: abs(v - 1.0))
        dist = abs(target - 1.0)
        return [i for i, v in enumerate(values) if abs(v - 1.0) == dist]
    else:
        raise ValueError(direction)
    return [i for i, v in enumerate(values) if v == target]


def load_numbers() -> dict[str, dict]:
    return {e["key"]: e for e in json.loads(NUMBERS_JSON.read_text(encoding="utf-8"))}


def build_main_table(numbers: dict[str, dict]) -> tuple[str, list[dict]]:
    """Returns (latex, report rows). Raises KeyError listing every missing key."""
    keys = [[tmpl.format(m=m) for m in MODELS] for (_, _, tmpl, _) in COLUMNS]
    missing = [k for col in keys for k in col if k not in numbers or numbers[k]["undefined"]]
    if missing:
        raise KeyError(f"numbers.json keys missing or undefined: {missing}")
    bold: list[set[int]] = []
    report: list[dict] = []
    for (grp, sub, tmpl, direction), col in zip(COLUMNS, keys):
        vals = [numbers[k]["value"] for k in col]
        b = best_indices(vals, direction)
        bold.append(set(b))
        fmts = [numbers[k]["formatted"] for k in col]
        dup = sorted({f for f in fmts if fmts.count(f) > 1})
        report.append({"column": f"{grp}/{sub}", "best_models": [MODELS[i] for i in b],
                       "identical_after_rounding": dup})
    lines = [
        "% Generated by scripts/make_paper_tables.py -- do not edit by hand.",
        "% Every numeric cell is a numbers-book macro (keys in paper/evidence/numbers.json).",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{TODO: caption}",
        "\\label{tab:main}",
        "\\begin{tabular}{l" + "c" * len(COLUMNS) + "}",
        "\\toprule",
    ]
    # Group header row: Model | 2 | 2 | 1 | 1 | 1
    spans: list[tuple[str, int]] = []
    for grp, *_ in COLUMNS:
        if spans and spans[-1][0] == grp:
            spans[-1] = (grp, spans[-1][1] + 1)
        else:
            spans.append((grp, 1))
    head = ["Model"] + [f"\\multicolumn{{{n}}}{{c}}{{{GROUP_HEADER[g]}}}" for g, n in spans]
    lines.append(" & ".join(head) + " \\\\")
    col = 2
    rules = []
    for _, n in spans:
        rules.append(f"\\cmidrule(lr){{{col}-{col + n - 1}}}")
        col += n
    lines.append("".join(rules))
    lines.append(" & " + " & ".join(sub for _, sub, _, _ in COLUMNS) + " \\\\")
    lines.append("\\midrule")
    for i, m in enumerate(MODELS):
        cells = []
        for c, k in enumerate(keys):
            cell = f"\\N{{{k[i]}}}"
            cells.append(f"\\textbf{{{cell}}}" if i in bold[c] else cell)
        lines.append(f"{MODEL_NAME[m]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines), report


def _fmt(x: float, nd: int = 3) -> str:
    return f"{x:.{nd}f}"


def build_supp_slopes() -> tuple[str, pd.DataFrame]:
    met = pd.read_csv(PROJECT_ROOT / "results/phase3b/calibration_metrics.csv")
    ci = pd.read_csv(PROJECT_ROOT / "results/phase3b/calibration_bootstrap_ci.csv")
    rows = []
    for frac in (1.0, 0.1):
        for ds in DATASETS_ALL5:
            for m in MODELS:
                r = met[(met.dataset == ds) & (met.model == m) & (met.fraction == frac)].iloc[0]
                c = ci[(ci.dataset == ds) & (ci.model == m) & (ci.fraction == frac)].iloc[0]
                if bool(r.separable):
                    s = i = "separable"
                else:
                    s = f"{_fmt(r.slope)} [{_fmt(c.slope_lo)}, {_fmt(c.slope_hi)}]"
                    i = f"{_fmt(r.intercept)} [{_fmt(c.intercept_lo)}, {_fmt(c.intercept_hi)}]"
                rows.append({"fraction": frac, "dataset": ds, "model": m, "slope_ci": s, "intercept_ci": i})
    df = pd.DataFrame(rows)
    return _longtable(df, "Pooled calibration slope and intercept, 95\\% bootstrap CI",
                      "results/phase3b/calibration_metrics.csv, results/phase3b/calibration_bootstrap_ci.csv"), df


def build_supp_noise() -> tuple[str, pd.DataFrame]:
    rob = pd.read_csv(PROJECT_ROOT / "results/phase3c/robustness_averaged.csv")
    cont = pd.read_csv(PROJECT_ROOT / "results/phase3d/noise_continuous/noise_cont_averaged.csv")
    rows = []
    for ds_set in ("ALL5", "NO_CKD"):
        for metric in ("auroc", "log_loss"):
            for m in MODELS:
                def cell(df: pd.DataFrame, kind: str) -> str:
                    r = df[(df.model == m) & (df.kind == kind) & np.isclose(df.level, 0.5)
                           & (df.metric == metric) & (df.dataset_set == ds_set)].iloc[0]
                    return f"{_fmt(r.degradation_mean, 4)} [{_fmt(r.degradation_ci_lo, 4)}, {_fmt(r.degradation_ci_hi, 4)}]"
                rows.append({"dataset_set": ds_set, "metric": metric, "model": m,
                             "original_noise": cell(rob, "noise"), "continuous_only": cell(cont, "noise_cont")})
    df = pd.DataFrame(rows)
    return _longtable(df, "Degradation (perturbed minus clean) at noise 0.5, original vs continuous-only noise",
                      "results/phase3c/robustness_averaged.csv, results/phase3d/noise_continuous/noise_cont_averaged.csv"), df


def _longtable(df: pd.DataFrame, caption: str, sources: str) -> str:
    esc = lambda s: str(s).replace("_", "\\_")
    lines = [f"% Generated by scripts/make_paper_tables.py. Sources: {sources}",
             "\\begin{table*}[t]", "\\centering", "\\scriptsize",
             f"\\caption{{{caption}}}", "\\begin{tabular}{" + "l" * len(df.columns) + "}", "\\toprule",
             " & ".join(esc(c) for c in df.columns) + " \\\\", "\\midrule"]
    for _, r in df.iterrows():
        lines.append(" & ".join(esc(v) for v in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(lines)


def main() -> None:
    print(f"sys.executable = {sys.executable}")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tex, report = build_main_table(load_numbers())
    (OUT_DIR / "table_main.tex").write_text(tex, encoding="utf-8", newline="\n")
    for r in report:
        print(r)
    for name, (tex_s, df) in (("supp_slopes_per_dataset", build_supp_slopes()),
                              ("supp_noise_comparison", build_supp_noise())):
        (OUT_DIR / f"{name}.tex").write_text(tex_s, encoding="utf-8", newline="\n")
        df.to_csv(OUT_DIR / f"{name}.csv", index=False, lineterminator="\n")
        print(f"wrote {name} ({len(df)} rows)")


if __name__ == "__main__":
    main()
