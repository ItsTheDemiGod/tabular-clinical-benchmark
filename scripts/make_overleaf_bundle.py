r"""Phase 4c: builds paper/overleaf_bundle.zip (git-ignored) for upload to Overleaf.

Contents (and nothing else): main.tex, sections/*.tex, references.bib, evidence/numbers.tex,
figures/*.pdf, tables/table_main.tex, BUNDLE_README.txt. The zip is deterministic (sorted
entries, fixed timestamps). Refuses to build if any bundled file contains '@' (no emails
are ever stored) or if an \input / \includegraphics target is missing from the bundle.
"""
from __future__ import annotations

import hashlib
import re
import sys
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
PAPER = PROJECT_ROOT / "paper"
ZIP_PATH = PAPER / "overleaf_bundle.zip"
FIXED_TIME = (2026, 11, 8, 0, 0, 0)

BUNDLE_README = r"""Overleaf bundle (generated by scripts/make_overleaf_bundle.py)

1. Overleaf: New Project -> Upload Project -> choose this zip.
2. Menu: main document = main.tex; compiler = pdfLaTeX. The IEEEtran class is
   available on Overleaf: switch the \documentclass line in main.tex to
   \documentclass[conference]{IEEEtran} and remove the article fallback and the
   \providecommand fallbacks (see the TODO comments in main.tex).
3. After uploading, add the author emails BY HAND in main.tex (the placeholders are
   [EMAIL]); emails are never stored in the repository.
4. Every result number must be written as \N{key} (evidence/numbers.tex).
5. Before submission, run locally on the .tex files:
   scripts/check_paper_numbers.py and scripts/check_paper_layout.py.
"""

_INPUT_RE = re.compile(r"\\input\{([^}]+)\}")
_EMAIL_RE = re.compile(rb"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
_GRAPHICS_RE = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}")


def bundle_members(paper: Path = PAPER) -> dict[str, bytes]:
    """Archive name -> bytes, for exactly the allowed files."""
    members: dict[str, bytes] = {}

    def add(rel: str) -> None:
        members[rel] = (paper / rel).read_bytes()

    for rel in ("main.tex", "references.bib", "evidence/numbers.tex", "tables/table_main.tex"):
        add(rel)
    for p in sorted((paper / "sections").glob("*.tex")):
        add(f"sections/{p.name}")
    for p in sorted((paper / "figures").glob("*.pdf")):
        add(f"figures/{p.name}")
    members["BUNDLE_README.txt"] = BUNDLE_README.encode("utf-8")
    return dict(sorted(members.items()))


def referenced_targets(members: dict[str, bytes]) -> list[tuple[str, str, str]]:
    """(source file, kind, target path inside the bundle) for every \\input / \\includegraphics,
    INCLUDING ones inside commented-out example environments (they must resolve too)."""
    out = []
    for name, data in members.items():
        if not name.endswith(".tex"):
            continue
        text = data.decode("utf-8")
        for m in _INPUT_RE.finditer(text):
            t = m.group(1)
            out.append((name, "input", t if t.endswith(".tex") else t + ".tex"))
        for m in _GRAPHICS_RE.finditer(text):
            out.append((name, "includegraphics", m.group(1)))
    return out


def check(members: dict[str, bytes]) -> list[str]:
    problems = []
    for src, kind, tgt in referenced_targets(members):
        if tgt not in members:
            problems.append(f"{src}: {kind} target {tgt!r} not in bundle")
    for name, data in members.items():
        if name.endswith(".pdf"):  # binary: '@' bytes are expected, so look for an email pattern
            if _EMAIL_RE.search(data):
                problems.append(f"{name}: contains an email-like pattern")
        elif b"@" in data:
            problems.append(f"{name}: contains '@' (possible email)")
    return problems


def build(zip_path: Path = ZIP_PATH, paper: Path = PAPER) -> Path:
    members = bundle_members(paper)
    problems = check(members)
    if problems:
        raise SystemExit("bundle refused:\n  " + "\n  ".join(problems))
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in members.items():
            zi = zipfile.ZipInfo(name, FIXED_TIME)
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, data)
    return zip_path


def main() -> None:
    print(f"sys.executable = {sys.executable}")
    path = build()
    with zipfile.ZipFile(path) as z:
        for zi in z.infolist():
            print(f"{zi.file_size:>9}  {zi.filename}")
    print(f"zip: {path.stat().st_size} bytes, sha256={hashlib.sha256(path.read_bytes()).hexdigest()}")
    print("path-resolution + no-'@' check: OK")


if __name__ == "__main__":
    main()
